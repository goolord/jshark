sigLines :: Text -> [Text] -> Text -> [Text]
sigLines name [] ret = [name <> " :: " <> ret]
sigLines name (t : ts) ret =
  (name <> " ::")
    : ("  " <> t)
    : fmap ("  -> " <>) (ts <> [ret])

showT :: Text -> Text
showT t = T.pack (show (T.unpack t))
